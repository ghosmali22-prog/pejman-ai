const dicts = { fa, en }
const KEY = 'pj-admin-lang'

interface I18n {
  lang: Lang
  t: Dict
  dir: 'rtl' | 'ltr'
  toggle: () => void
  /** Localised number (Persian digits in fa). */
  n: (v: number) => string
  /** Localised date, Persian (Jalali) calendar in fa. */
  date: (v: string | Date, opts?: Intl.DateTimeFormatOptions) => string
}

const Ctx = createContext<I18n | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      return (localStorage.getItem(KEY) as Lang) || 'fa'
    } catch {
      return 'fa'
    }
  })

  useEffect(() => {
    try {
      localStorage.setItem(KEY, lang)
    } catch {
      /* ignore */
    }
  }, [lang])

  const toggle = useCallback(() => setLang((l) => (l === 'fa' ? 'en' : 'fa')), [])

  const value = useMemo<I18n>(() => {
    const locale = lang === 'fa' ? 'fa-IR-u-ca-persian' : 'en-GB'
    const num = new Intl.NumberFormat(lang === 'fa' ? 'fa-IR' : 'en-US')
    return {
      lang,
      t: dicts[lang],
      dir: lang === 'fa' ? 'rtl' : 'ltr',
      toggle,
      n: (v) => num.format(v),
      date: (v, opts = { day: 'numeric', month: 'short', year: 'numeric' }) =>
        new Intl.DateTimeFormat(locale, opts).format(typeof v === 'string' ? new Date(v) : v),
    }
  }, [lang, toggle])

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n() {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error('useI18n must be used inside <I18nProvider>')
  return ctx
}
